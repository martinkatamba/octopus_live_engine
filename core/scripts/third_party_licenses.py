#!/usr/bin/env python3
"""Writes the licence notices of every crate compiled into a build.

The Python wheel (and any native library we ship) links its Rust
dependencies statically, and their licences (MIT, Apache-2.0, BSD, ...)
require their notices to travel with the binary. This collects each
crate's licence files from the cargo registry and writes them to one file,
each distinct text once, with the crates that use it.

    core/scripts/third_party_licenses.py                  # the Python wheel
    core/scripts/third_party_licenses.py --features duckdb
    core/scripts/third_party_licenses.py --check          # exit 1 if out of date

Run it after changing dependencies or features; `--check` is for CI.
"""

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

CORE = Path(__file__).resolve().parent.parent
DEFAULT_MANIFEST = CORE / "bindings" / "python" / "Cargo.toml"
DEFAULT_OUT = CORE / "bindings" / "python" / "THIRD_PARTY_LICENSES.txt"
NOTICE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "unlicense")


def shipped_crates(manifest: Path, features: str) -> list:
    """The crates linked into the build: normal dependencies of the root,
    without build scripts' dependencies, dev dependencies, proc macros or
    our own workspace crates."""
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", str(manifest)]
    if features:
        cmd += ["--features", features]
    meta = json.loads(subprocess.run(cmd, check=True, capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    ours = set(meta["workspace_members"])
    seen, stack = set(), [meta["resolve"]["root"]]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    crates = []
    for pid in seen - ours:
        p = packages[pid]
        if any("proc-macro" in t["kind"] for t in p["targets"]):
            continue
        crates.append(p)
    return sorted(crates, key=lambda p: (p["name"], p["version"]))


def notice_files(p: dict) -> list:
    root = Path(p["manifest_path"]).parent
    files = {f for f in root.iterdir() if f.is_file() and f.name.lower().startswith(NOTICE_PREFIXES)}
    if p.get("license_file"):
        files.add((root / p["license_file"]).resolve())
    return sorted(files)


def render(crates: list, features: str) -> str:
    texts = {}  # sha256 -> (text, [crate labels])
    missing = []
    for p in crates:
        label = f"{p['name']} {p['version']} ({p.get('license') or 'see text'})"
        files = notice_files(p)
        if not files:
            missing.append(label)
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").strip() + "\n"
            key = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(key, (text, []))[1].append(f"{label}: {f.name}")
    out = [
        "Third-party licences",
        "====================",
        "",
        "The octopus-core native library includes the Rust crates below, each",
        "under its own licence. Generated by core/scripts/third_party_licenses.py",
        f"(features: {features or 'default'}); do not edit by hand.",
        "",
        f"{len(crates)} crates:",
        "",
    ]
    out += [f"  {p['name']} {p['version']}  {p.get('license') or 'see text'}" for p in crates]
    for text, users in sorted(texts.values(), key=lambda t: sorted(t[1])[0]):
        out += ["", "-" * 78, "", "Used by:"]
        out += [f"  {u}" for u in sorted(users)]
        out += ["", text.rstrip()]
    if missing:
        out += ["", "-" * 78, "", "These crates ship no licence file; their licence is the SPDX expression shown:"]
        out += [f"  {m}" for m in missing]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--features", default="")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is not up to date")
    args = ap.parse_args()
    text = render(shipped_crates(args.manifest, args.features), args.features)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
